/**
 * Arts & performance pre-college programs for high school students.
 *
 * ---------------------------------------------------------------------------
 * WHY THIS CATEGORY EXISTS SEPARATELY
 * ---------------------------------------------------------------------------
 * The source list this catalog was built from had no arts category at all —
 * music and theatre appeared as a handful of university band camps filed under
 * Humanities. That gap is worth naming, because arts pre-college is one of the
 * most aggressively monetised corners of admissions. A family can be quoted
 * $8,000–$12,000 for four to six weeks and told, in marketing copy, that the
 * summer is career-defining.
 *
 * It is also, quietly, where some of the most generous programs in the whole
 * catalog live. NYO-USA and Sphinx are free including room, board and travel.
 * Juilliard MAP and Berklee City Music are tuition-free. Museum teen programs
 * in almost every large US city are free, and a striking number of them PAY the
 * student a stipend or hourly wage.
 *
 * Both facts belong on the same page. A student should be able to see at a
 * glance that a free paid museum internship and a $10,000 portfolio intensive
 * are not the same kind of thing, whatever either one's website implies.
 *
 * ---------------------------------------------------------------------------
 * FIELDS SPECIFIC TO THIS CATEGORY
 * ---------------------------------------------------------------------------
 * `eligibility` states an AUDITION or PORTFOLIO requirement wherever one
 * exists. This is not a detail — it changes the planning horizon. A student who
 * learns in April that a January deadline required a recorded audition has lost
 * a year. Where a program requires prepared repertoire or a body of work, the
 * real preparation starts months before the deadline listed here.
 *
 * `openEnrollment: true` marks programs that admit essentially everyone who
 * pays. It is set only where the host's own materials describe the program as
 * open to all levels with no audition or portfolio screen. Where a program
 * auditions, the field is left unset rather than guessed at.
 *
 * The cost enum, the deadline/deadlineISO distinction, and the rule against
 * inventing any field are documented in index.js and followed here. "" and
 * "unknown" are used as honest answers throughout.
 */

